/**
 * Strips parenthetical subtitles from long tradition titles for single-line headers, chips, and badges.
 */
export function compactTraditionName(name?: string): string {
  if (!name) return '';
  return name.replace(/\s*[（(][^）)]*[）)]\s*$/, '').trim();
}

